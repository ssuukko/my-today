import { test, expect } from '@playwright/test'

test('anonymous screens, protected routes and outage at mobile and desktop sizes', async ({ page }) => {
  await page.route('**/api/v1/auth/session', route => route.fulfill({ status: 401, contentType: 'application/json', body: '{}' }))
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/welcome')
    await expect(page.getByRole('heading', { name: '오늘을 조금 더 나답게.' })).toBeVisible()
    await expect(page.getByRole('link', { name: '로그인', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.goto('/money')
  await expect(page).toHaveURL(/\/login\?next=/)
  await expect(page.getByLabel('이메일', { exact: true })).toBeVisible()
  await page.route('**/api/v1/auth/session', route => route.fulfill({ status: 503, body: '{}' }))
  await page.reload()
  await expect(page.getByRole('heading', { name: '연결을 확인해 주세요' })).toBeVisible()
  await expect(page.getByRole('button', { name: '다시 시도' })).toBeVisible()
  await page.route('**/api/v1/auth/session', route => route.fulfill({ status: 401, body: '{}' }))
  await page.getByRole('button', { name: '다시 시도' }).click()
  await expect(page).toHaveURL(/\/login/)
  await expect(page.getByLabel('이메일', { exact: true })).toBeVisible()
})

test('real API invitation, login, onboarding, profile and logout', async ({ page }) => {
  test.skip(!process.env.E2E_INVITE_TOKEN, 'Requires running API and an explicit development invite')
  await page.goto('/signup')
  const email = `browser-${Date.now()}@example.test`
  await page.getByLabel('표시 이름', { exact: true }).fill('테스트 사용자')
  await page.getByLabel('이메일', { exact: true }).fill(email)
  await page.getByLabel('비밀번호', { exact: true }).fill('my-private-test-password')
  await page.getByLabel('비밀번호 확인', { exact: true }).fill('my-private-test-password')
  await page.getByLabel('초대 코드', { exact: true }).fill(process.env.E2E_INVITE_TOKEN!)
  await page.getByRole('button', { name: '계정 만들기' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('이메일', { exact: true }).fill(email)
  await page.getByLabel('비밀번호', { exact: true }).fill('my-private-test-password')
  await page.getByRole('button', { name: '로그인', exact: true }).click()
  await expect(page).toHaveURL(/\/onboarding/)
  await page.getByRole('button', { name: '오늘 시작하기' }).click()
  await expect(page).toHaveURL(/\/today$/)
  await expect(page.getByRole('heading', { name: /테스트 사용자님/ })).toBeVisible()
  await page.goto('/settings')
  await expect(page.getByText(email, { exact: true })).toBeVisible()
  await page.getByLabel('표시 이름', { exact: true }).fill('변경된 이름')
  await page.getByRole('button', { name: '설정 저장' }).click()
  await expect(page.getByRole('status')).toHaveText('설정을 저장했습니다.')
  await page.getByRole('button', { name: '로그아웃' }).click()
  await expect(page).toHaveURL(/\/welcome$/)
  await page.goto('/today')
  await expect(page).toHaveURL(/\/login/)
})
